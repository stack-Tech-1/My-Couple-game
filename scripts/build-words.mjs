// Regenerates src/content/words/valid5.ts from the MIT-licensed `word-list` package.
// Words are packed into one string: every entry is exactly 5 letters, so no separators.
import fs from "node:fs";
const words = fs.readFileSync("node_modules/word-list/words.txt", "utf8").split("\n").filter((w) => /^[a-z]{5}$/.test(w));
const out = `// Generated by scripts/build-words.mjs from the MIT-licensed word-list package. Do not edit.
/** ${words.length} valid five-letter guesses, packed: word i is PACKED.slice(i * 5, i * 5 + 5). */
export const PACKED = "${words.join("")}";
`;
fs.writeFileSync("src/content/words/valid5.ts", out);
console.log(`wrote ${words.length} words`);